#!/usr/bin/env python3
"""Popo speaks in his Fishing Frenzy voice: python3 tools/build-popo-voice.py

In Fishing Frenzy (~/Downloads/popo-fishing/fishing-frenzy) Popo's lines were made in the "Ai Wala
Human By Aamir" studio: Gemini's Puck with a Hindi script, so the English comes out with an Indian
accent, 10% deeper than Swiftee so he is a bigger, warmer bear. He never gives instructions there;
he only reacts, in a few comic words: "Great catch!", "Whoopsie Doopsie!", "Huh?!", "Woah!", "Wow!
What a catch!". This copies those clips out of Fishing Frenzy's voice data into this game's
src/voice-data.js under the same keys (speaker and on-screen text, as audio.js voiceKey() makes
them), replacing the old Kokoro takes. tools/build-voice.py runs it after writing the file, so a
rebuild keeps them. The narrator's lines are this game's own and are left alone.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'voice-data.js'
FRENZY = Path.home() / 'Downloads' / 'popo-fishing' / 'fishing-frenzy' / 'parts'
SOURCES = [FRENZY / 'fishing-2' / 'src' / 'voice-data.js', FRENZY / 'fishing-1' / 'src' / 'voice-data.js']

# Popo's lines in this game (as on screen), all recorded in Fishing Frenzy
LINES = ['*Great* catch!', 'Whoopsie Doopsie!', 'Huh?!', '*Woah!*', '*Wow!*', 'What a *catch!*']
# his lines from before, no longer said
RETIRED = ['We caught them *all*!']

ENTRY = re.compile(r'^\s*("(?:[^"\\]|\\.)*"):\s*("data:audio/[^"]*"),?\s*$')


def voice_key(who, text):
    """Must match voiceKey() in src/audio.js."""
    text = text.replace('*', '').replace('…', '...').replace('’', "'")
    return f"{who}:{' '.join(text.split())}".lower()


def read(path):
    clips = {}
    for line in path.read_text().splitlines():
        m = ENTRY.match(line)
        if m:
            clips[json.loads(m.group(1))] = json.loads(m.group(2))
    return clips


def studio_clips():
    """Popo's clips from Fishing Frenzy, keyed as this game looks them up."""
    found = {}
    for source in SOURCES:
        if source.exists():
            for key, url in read(source).items():
                found.setdefault(key, url)
    clips = {}
    for text in LINES:
        key = voice_key('popo', text)
        if key not in found:
            sys.exit(f'Fishing Frenzy has no clip for Popo saying {text!r} ({key})')
        clips[key] = found[key]
    return clips


def merge(path=DATA):
    clips = read(path)
    for text in RETIRED:
        clips.pop(voice_key('popo', text), None)
    popo = studio_clips()
    clips.update(popo)
    with open(path, 'w') as fh:
        fh.write('// Generated by tools/build-voice.py (and tools/build-popo-voice.py for Popo): recorded\n')
        fh.write('// voice lines as data URLs, keyed by speaker and on-screen text (see voiceKey in\n')
        fh.write('// src/audio.js). Do not edit by hand.\n')
        fh.write('window.PopoGame = window.PopoGame || {};\nPopoGame.VOICE_DATA = {\n')
        for k, v in clips.items():
            fh.write(f'  {json.dumps(k)}: {json.dumps(v)},\n')
        fh.write('};\n')
    for key in popo:
        print(f'popo (Fishing Frenzy studio): {key}')


if __name__ == '__main__':
    merge()
